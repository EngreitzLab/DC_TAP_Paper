    def make_grna_bigwig(bed: str,window: int, viewport: int = 1000) -> str:
        """
        Function to make a gRNA bigWig file where the signal is SCEPTRE analyzed 
        % Change Effect Size (PC) for deepTools usage compatibility.

        Parameters
        ----------
        bed : str filepath of grna bed file where the genomic coordinates (hg38) interval is a gRNA's PAM
        window : int that denotes the base-pair window to expand the gRNA PAM for averaging overlapping PC

        EXPECTED INPUT STRUCTURE
        ------------------------
        see method `_preprocess_mkbed_grna_for_deeptools()`.
        However, for this function to work, only `chr`, `start`, `end`, `name`, and `score` is required.
        The rest of the columns are optional.
        """
        dir = Path(bed).parent
        fbed = Path(Path(bed).stem)
        fbed_window = Path(f"{fbed}-{window}bp.bed")
        fbed_merged = Path(f"{fbed}-{window}bp-merged.bed")
        fbed_bp = Path(f"{fbed}-{window}bp-1bp-windows.bed")
        fbed_bg = Path(f"{fbed}-{window}bp.bedGraph")
        fbed_bw = Path(f"{fbed}-{window}bp.bigWig")

        # Expand intervals by window
        bed = (
            BedTool(bed)
                .slop(genome="hg38", l=window, r=window)
                .saveas(dir / fbed_window)
        )

        # Sort & overwrite file in-place
        tmp = fbed_window.with_suffix(fbed_window.suffix + ".tmp")
        with open(tmp, "w") as o:
            subprocess.run([
                "sort", "-k", "1,1", "-k2,2n", dir / fbed_window
            ], check=True, stdout=o)
        os.replace(tmp, dir / fbed_window)

        # Merge for minimal intervals to make 1bp interval
        bed = (
            BedTool(MACS3_DS)
                .slop(genome="hg38", l=viewport, r=viewport)
                .intersect(bed, wa=True)
                .merge().saveas(dir / fbed_merged)
        )

        # Make 1bp windows and assign gRNA effect
        bed = BedTool().makewindows(b=bed, w=1).saveas(dir / fbed_bp)

        # Map overlapping gRNA effect sizes and compute mean at 1-bp resolution
        bed = BedTool().map(a=bed, b=BedTool(dir / fbed_window), c=5, o="mean", null=0).saveas(dir / fbed_bg)

        # Fetch hg38 chromsizes
        chromsizes = fetch_chromsizes("hg38")

        # Convert bedGraph to bigWig
        subprocess.run([
            "bedGraphToBigWig", f"{dir / fbed_bg}", chromsizes, f"{dir / fbed_bw}"
        ])

        return str(dir / fbed_bw)
    
