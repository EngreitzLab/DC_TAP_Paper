    def min_max_normalize_bedgraph(in_path: Path, out_path: Path) -> None:
        vmin = float("inf")
        vmax = float("-inf")

        # First pass: find min and max
        with in_path.open() as f:
            for line in f:
                if not line.strip():
                    continue
                fields = line.rstrip("\n").split("\t")
                val = float(fields[3])
                if val < vmin:
                    vmin = val
                if val > vmax:
                    vmax = val

        if vmax == vmin:
            # Avoid divide-by-zero; treat everything as 0 or 1 as you prefer
            scale = 1.0
        else:
            scale = vmax - vmin

        # Second pass: write normalized values
        with in_path.open() as fin, out_path.open("w") as fout:
            for line in fin:
                if not line.strip():
                    continue
                fields = line.rstrip("\n").split("\t")
                val = float(fields[3])
                norm = (val - vmin) / scale
                fields[3] = f"{norm:.6f}"
                fout.write("\t".join(fields) + "\n")

    def normalize_bigwig(inputs: list[str], method: str, outdir: str) -> list[str]:
        """
        naive method expected to take >1hr to run.

        note the dnase track has some non standard chr labels
        e.g. chrEBV etc. this breaks convert bedgraph to bigwig
        b/c hg38.chrom.sizes does not have those annotations
        """
        # methods = {
        #     "min-max" : min_max_normalize
        # }

        tmp_dir = Path(outdir) / "tmp-norm-bigwig"
        cs.mkdir(tmp_dir)

        chrom_sizes = fetch_chromsizes("hg38")

        # Convert to BedGraph
        # for bw in inputs:
        #     cmd = ["bigWigToBedGraph", bw, f"{tmp_dir / Path(bw).stem}.bedGraph"]
        #     subprocess.run(cmd)

        out_bws: list[str] = []
        done = tmp_dir / "normalized.DONE"

        if cs.file_exist(done):
            outs = list(tmp_dir.glob("*.bigWig"))
            outs = [str(o) for o in outs]
            return outs

        for bw in inputs:
            bw_path = Path(bw)
            stem = bw_path.stem

            # 1) bigWig -> bedGraph
            bedgraph = tmp_dir / f"{stem}.bedGraph"
            # cmd = ["bigWigToBedGraph", str(bw_path), str(bedgraph)]
            # subprocess.run(cmd, check=True)

            # 2) min–max normalize bedGraph
            norm_bedgraph = tmp_dir / f"{stem}.minmax.norm.bedGraph"
            min_max_normalize_bedgraph(bedgraph, norm_bedgraph)

            # 3) bedGraph -> bigWig
            out_bw = tmp_dir / f"{stem}.minmax.norm.bigWig"
            cmd = ["bedGraphToBigWig", str(norm_bedgraph), chrom_sizes, str(out_bw)]
            subprocess.run(cmd, check=True)

            out_bws.append(str(out_bw))

        done.touch()
        return out_bws
    return


