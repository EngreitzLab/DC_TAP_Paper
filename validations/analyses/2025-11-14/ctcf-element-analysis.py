    def _preprocess_singleton_mkbed_pamcoords(df2, g1):
        """
        Method to get the PAM genomic coordinates (hg38) 
        of the gRNA after alignment
        """
        # I/O
        dir = "results/2025-11-14/ctcf-analysis-intermediates/"
        fastq_o = "results/2025-11-14/ctcf-analysis-intermediates/wtc-grna-pam.fastq"
        psl_o = "results/2025-11-14/ctcf-analysis-intermediates/wtc-grna-pam.psl"
        bed_o = "results/2025-11-14/ctcf-analysis-intermediates/wtc-grna-pam-fullseq.bed"
        cs.mkdir(dir)

        # Align gRNA sequence to reference genome using blat
        df_tmp = df2.copy().drop_duplicates(subset=[g1])
        bs.mkfastq_for_blat(df_tmp, o1, g1, fastq_o)
        bs.blat(fastq_o, psl_o)
        bs.convert_psl_to_bed(psl_o, bed_o)

        # Find the PAM coordinates based off strand
        fullseq = pd.read_csv(bed_o, sep="\t", header=None)
        fullseq[1] = np.where(fullseq[5] == "+", fullseq[2] - 3, fullseq[1])
        fullseq[2] = np.where(fullseq[5] == "+", fullseq[2], fullseq[1] + 3)

        # Write to Storage
        pam = BedTool.from_dataframe(fullseq)
        pam.saveas(final_out2)

    def _preprocess_singleton_merge_pamcoords(df2, pam, dict, key):
        """
        Helper method to merge singleton pamcoord columns to singleton df.
        """
        g1 = key
        df2 = df2.merge(
            pam[list(dict.values())],
            left_on=[g1],
            right_on=[g1],
            how="left"
        )
        return df2

    def _preprocess_singleton_expand_pamcoords(pam, offset, colname_dict, out):
        """
        Method to expand PAM genomic coordinates by an offset.
        """
        # Expand PAM genomic coords by offset using BedTools slop
        pam = BedTool.from_dataframe(pam).slop(genome="hg38", l=offset, r=offset).to_dataframe()

        # Offset coordinate window by +/-150-bp
        pam = _preprocess_singleton_expand_pamcoords(pam, offset)

        # Write to Results
        pam.saveas(out)

        ## Rename column header
        pam.columns = range(pam.shape[1])
        pam = pam.rename(columns=colname_dict)

        return pam

    def _preprocess_singleton():
        # Inputs
        df1 = raw_wtc11_grna_design.copy()
        df2 = raw_wtc11_singleton.copy()

        # GOAL 1: 
        # For each singleton gRNA, get the guide sequence with PAM from the design file
        m1 = "name"
        o1 = "GuideSequenceWithPAM"
        g1 = "grna_id"

        ## Rename ID to match Table S3 standards and obtain GuideSequenceWithPAM col
        df1[m1] = df1[m1].str.replace(
            "WTC11_Random_Screen_sgOpti-DC",
            "WTC11_Random_Screen_Crop",
            regex=False
        )
        df1 = df1.loc[:, [m1, o1]]
        df1 = df1.set_index(m1)

        ## Merge df1 and df2
        df2[o1] = df2[g1].map(df1[o1])


        # GOAL 2: 
        # Get the PAM genomic coordinates (hg38) of the gRNA after alignment
        final_out2 ="results/2025-11-14/2025-11-20-dctapseq-validation-wtc11-grna-pam.bed"
        if not cs.file_exist(final_out2):
            _preprocess_singleton_mkbed_pamcoords(df2, g1)

        # GOAL 3: 
        # Merge PAM genomic coordinates to singleton dataframe
        p3_dict = {
            0 : "pamcoords_chr",
            1 : "pamcoords_start",
            2 : "pamcoords_end",
            3 : g1,
            #4 : "score?",
            5 : "pamcoords_strand"
        }
        pam = pd.read_csv(final_out2, sep="\t", header=None).rename(columns=p3_dict)

        ## Merge columns using g1 = "grna_id"
        df2 = _preprocess_singleton_merge_pamcoords(df2, pam, p3_dict, key = g1)

        return df2

    def _preprocess_singleton_merge(df_s3, df_sing):
        """
        Helper Method to merge Singleton to Table S3 and format column names.
        """
        # Split comma-separated guide_ids into lists
        df_s3["guide_list"] = df_s3["guide_ids"].str.split(",")

        # Explode to one row per guid
        df_s3_expanded = df_s3.explode("guide_list")
        df_s3_expanded["guide_list"] = df_s3_expanded["guide_list"].str.strip()

        # Select singleton columns
        cols = [
            "grna_id",
            "pass_qc",
            "response_id",
            "pct_change_effect_size",
            "n_nonzero_trt",
            "n_nonzero_cntrl",
            "standard_error_pct_change",
            "GuideSequenceWithPAM"
        ]
        cols.extend([c for c in df_sing.columns if c.startswith("pamcoords")])

        # Merge with df_sing to get effect_size for each guide
        merged = df_s3_expanded.merge(
            df_sing[cols],
            left_on=["guide_list", "gene_id"],
            right_on=["grna_id", "response_id"],
            how="left",
        )

        # Re-label column names
        merged = merged.rename(
            columns={
                "pass_qc" : "singleton_pass_qc",
                "response_id": "singleton_response_id",
                "pct_change_effect_size_x": "pct_change_effect_size",  # fix original colname
                "pct_change_effect_size_y": "singleton_pct_change_effect_size",
                "n_nonzero_trt": "singleton_n_nonzero_trt",
                "n_nonzero_cntrl": "singleton_n_nonzero_cntrl",
                "standard_error_pct_change_x": "standard_error_pct_change",  # fix original colname
                "standard_error_pct_change_y": "singleton_standard_error_pct_change",
            }
        )

        return merged 

    def _preprocess_mkbed_grna_for_deeptools(dfi_sig_wtc11_grna):
        df = dfi_sig_wtc11_grna.copy()

        # Drop all singleton that did not pass SCEPTRE QC
